import { createRequire } from "node:module";
import { mkdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { pathToFileURL } from "node:url";
const root = path.resolve(import.meta.dirname, ".."), require = createRequire(path.join(root, "apps/desktop/package.json"));
const { build } = require("esbuild");
const output = path.join(root, "artifacts/scene-director-live.mjs");
await mkdir(path.dirname(output), { recursive: true });
await build({ stdin: { contents: 'export { directSceneComposition } from "./apps/desktop/src/ai/sceneDirector"; export { createFallbackWorldBlueprints, compileWorldBlueprint } from "./apps/desktop/src/domain/worldForge"; export { createStarterCampaign } from "./apps/desktop/src/domain/seed";', resolveDir: root }, outfile: output, bundle: true, platform: "node", format: "esm" });
const { directSceneComposition, createFallbackWorldBlueprints, compileWorldBlueprint, createStarterCampaign } = await import(pathToFileURL(output));
const description = process.env.DNDROM_SCENE_PROMPT || "An ancient Chinese village with timber courtyard houses, curved jade tile roofs, a ceremonial gate and a small shrine in a bamboo forest";
const [blueprint] = createFallbackWorldBlueprints({ description, kind: "auto", size: "small", gridShape: "square", seed: 7241, background: "none" });
const settings = { ...createStarterCampaign().settings, useLocalAiForMaps: true, localAiEndpoint: process.env.DNDROM_LOCAL_ENDPOINT || "http://127.0.0.1:11435/v1", localAiModel: process.env.DNDROM_LOCAL_MODEL || "qwen2.5-coder:7b" };
const started = Date.now();
const originalFetch = globalThis.fetch;
let requestIndex = 0;
globalThis.fetch = async (...args) => {
  const response = await originalFetch(...args);
  const payload = await response.clone().json();
  await writeFile(path.join(root, `artifacts/scene-director-response-${++requestIndex}.json`), JSON.stringify(payload, null, 2));
  console.log(JSON.stringify({ stage: requestIndex, status: response.status, finish: payload.choices?.[0]?.finish_reason, tokens: payload.usage }));
  return response;
};
const result = await directSceneComposition(blueprint, settings);
await writeFile(path.join(root, "artifacts/scene-director-result.json"), JSON.stringify(result, null, 2));
if (result.provider !== "local-ai") throw new Error(result.warning || "Local scene director fell back");
const compiled = compileWorldBlueprint(result.blueprint);
await writeFile(path.join(root, "artifacts/scene-director-world.json"), JSON.stringify(compiled.map));
console.log(JSON.stringify({ elapsedSeconds: (Date.now() - started) / 1000, model: settings.localAiModel, design: result.blueprint.composition.design, recipes: result.blueprint.composition.recipes.map((recipe) => ({ name: recipe.name, parts: recipe.parts.length })), assemblies: compiled.map.entities.filter((entity) => entity.worldGeometry?.kind === "assembly").length, validation: compiled.validation }, null, 2));
